#!/usr/bin/env bash
# ==============================================================================
# get_job_url.sh - 查詢正在運行的 Code-Server Slurm 作業之連線網址
# ==============================================================================
set -euo pipefail

URL_JOB_FILE="${HOME}/.code-server-slurm-url.txt"

echo "========================================================"
echo "🔍 查詢正在運行的 code-server 作業..."
echo "========================================================"

# 1. 檢查 Slurm 佇列
JOBS=$(squeue -u "$(whoami)" --name=code-server -o "%.10i %.10P %.12j %.8T %.10M %.12R" || true)

echo "${JOBS}"
echo "--------------------------------------------------------"

# 2. 若有儲存的最新連線網址，印出
if [ -f "${URL_JOB_FILE}" ]; then
    echo "📋 最新排程產生的 OOD 連線網址:"
    cat "${URL_JOB_FILE}"
else
    echo "ℹ️ 若作業剛送出，請稍候 5~10 秒讓計算節點啟動並寫入網址檔。"
fi
echo "========================================================"
